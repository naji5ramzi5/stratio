"""
rich/signal_bridge.py — Bot4 to Bot5 Signal Ingestion Bridge.

Listens for and ingests signals generated by Bot4:
  - Supports file-based polling (`master_signals.json` or `market_events/`),
    direct memory push, and JSON payload deserialization.
  - Converts raw incoming payloads into validated `SignalContract` models.
  - Implements strict deduplication against `RichDB` to guarantee idempotency.
"""
from __future__ import annotations

import json
import logging
import os
from datetime import datetime, timezone
from decimal import Decimal
from typing import Callable, Dict, List, Optional

from .config import RichConfig
from .db import RichDB
from .models import SignalContract, TradeSide

logger = logging.getLogger("rich.signal_bridge")


class SignalBridge:
    """
    Decoupled bridge that ingests signals from Bot4 and hands them to Bot5.
    """

    def __init__(self, config: RichConfig, db: RichDB):
        self._config = config
        self._db = db
        self._seen_signals: set = set()
        self._signal_file_path = os.path.join(
            os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
            "master_signals.json"
        )

    def parse_signal(self, data: dict) -> Optional[SignalContract]:
        """
        Parse raw signal dictionary into typed SignalContract.
        """
        try:
            signal_id = data.get("signal_id") or data.get("id") or f"sig_{data.get('symbol')}_{int(datetime.now(timezone.utc).timestamp())}"
            raw_side = data.get("side", data.get("direction", "BUY")).upper()
            side = TradeSide.BUY if raw_side in ("BUY", "LONG") else TradeSide.SELL

            return SignalContract(
                signal_id=signal_id,
                symbol=data["symbol"].upper(),
                side=side,
                status=data.get("status", "TRADE_READY"),
                predicted_change_pct=Decimal(str(data.get("predicted_change_pct", data.get("expected_return_pct", "0.02")))),
                model_confidence=float(data.get("model_confidence", data.get("confidence", 0.8))),
                ensemble_agreement=float(data.get("ensemble_agreement", 1.0)),
                regime=data.get("regime", "NORMAL"),
                strategy_version=data.get("strategy_version", "v1.0"),
                created_at=data.get("created_at") or data.get("timestamp") or datetime.now(timezone.utc).isoformat(),
                expires_at=data.get("expires_at"),
                entry_reference=Decimal(str(data.get("entry_reference", data.get("price", "0")))) if data.get("entry_reference") or data.get("price") else None,
                suggested_stop_loss=Decimal(str(data["suggested_stop_loss"])) if "suggested_stop_loss" in data and data["suggested_stop_loss"] is not None else None,
                suggested_tp1=Decimal(str(data["suggested_tp1"])) if "suggested_tp1" in data and data["suggested_tp1"] is not None else None,
                suggested_tp2=Decimal(str(data["suggested_tp2"])) if "suggested_tp2" in data and data["suggested_tp2"] is not None else None,
                suggested_tp3=Decimal(str(data["suggested_tp3"])) if "suggested_tp3" in data and data["suggested_tp3"] is not None else None,
            )
        except Exception as exc:
            logger.error(f"[SignalBridge] Failed to parse signal: {exc} | data={data}")
            return None

    def poll_signals_file(self) -> List[SignalContract]:
        """
        Poll `master_signals.json` for new TRADE_READY signals.
        Supports both JSON Lines and JSON array.
        """
        if not os.path.exists(self._signal_file_path):
            return []

        items = []
        try:
            with open(self._signal_file_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        parsed = json.loads(line)
                        if isinstance(parsed, list):
                            items.extend(parsed)
                        elif isinstance(parsed, dict):
                            items.append(parsed)
                    except json.JSONDecodeError:
                        continue
        except Exception as exc:
            logger.warning(f"[SignalBridge] Error reading signals file: {exc}")
            return []

        valid_contracts: List[SignalContract] = []


        for item in items:
            if not isinstance(item, dict):
                continue
            contract = self.parse_signal(item)
            if not contract:
                continue

            # In-memory and DB deduplication
            if contract.signal_id in self._seen_signals:
                continue

            self._seen_signals.add(contract.signal_id)
            valid_contracts.append(contract)

        return valid_contracts
